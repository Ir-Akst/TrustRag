from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Iterator, Optional, Union

from trustrag.data.acquisition.hf import HFAcquisitionHelper
from trustrag.data.acquisition.local import LocalFileImporter
from trustrag.data.base import BaseAdapter, DatasetMetadata
from trustrag.data.exceptions import ValidationError
from trustrag.data.schemas import ClaimVerificationRecord

LABEL_MAP: Dict[str, str] = {
    "yes": "HALLUCINATED",
    "true": "HALLUCINATED",
    "1": "HALLUCINATED",
    "hallucinated": "HALLUCINATED",
    "no": "FACTUAL",
    "false": "FACTUAL",
    "0": "FACTUAL",
    "factual": "FACTUAL",
}


class HaluEvalAdapter(BaseAdapter):
    """Adapter for HaluEval hallucination evaluation benchmark."""

    metadata = DatasetMetadata(
        name="halueval",
        category="hallucination",
        description="HaluEval: 35k hallucinated and normal responses generated by LLMs across QA, dialogue, and summarization",
        source_uri="pminervini/HaluEval",
        license="MIT",
        access_type="open",
        record_type="ClaimVerificationRecord",
        paper_reference="Li et al., 2023 (EMNLP)",
        known_limitations="Model-generated hallucinations; paired synthetic samples",
        default_config="qa",
        default_splits=["data"],
        permitted_for_training=True,
        permitted_for_evaluation=True,
    )

    def __init__(
        self,
        *,
        split: str = "data",
        limit: Optional[int] = None,
        cache_dir: Optional[Union[str, Path]] = None,
        offline: bool = False,
        local_path: Optional[Union[str, Path]] = None,
        config_name: Optional[str] = None,
    ) -> None:
        super().__init__(
            split=split,
            limit=limit,
            cache_dir=cache_dir,
            offline=offline,
            config_name=config_name,
        )
        self.local_path = Path(local_path) if local_path else None

    def acquire(self) -> Any:
        if self.local_path and self.local_path.exists():
            return self.local_path
        return self.cache_dir

    def load_raw(self) -> Iterator[Dict[str, Any]]:
        if self.local_path and self.local_path.exists():
            yield from LocalFileImporter.read_records(self.local_path, limit=self.limit)
            return

        yield from HFAcquisitionHelper.load_hf_records(
            self.metadata.source_uri,
            split=self.split,
            config_name=self.config_name or "qa",
            cache_dir=self.cache_dir,
            limit=self.limit,
            offline=self.offline,
        )

    def transform(self, raw_item: Dict[str, Any]) -> Iterator[ClaimVerificationRecord]:
        doc = str(raw_item.get("knowledge") or raw_item.get("document") or raw_item.get("context") or "")
        query = str(raw_item.get("question") or raw_item.get("query") or "")
        item_id = str(raw_item.get("id") or raw_item.get("source_id") or "")

        # If item has separate right_answer and hallucinated_answer pairs
        right_answer = raw_item.get("right_answer")
        hallucinated_answer = raw_item.get("hallucinated_answer")

        if right_answer and hallucinated_answer:
            # Emit factual claim
            yield ClaimVerificationRecord(
                record_id=f"{item_id}_factual" if item_id else "factual",
                document=doc,
                claim=str(right_answer),
                label="FACTUAL",
                source_dataset=self.metadata.name,
                source_split=self.split,
                source_id=item_id,
                metadata={"query": query},
            )
            # Emit hallucinated claim
            yield ClaimVerificationRecord(
                record_id=f"{item_id}_hallucinated" if item_id else "hallucinated",
                document=doc,
                claim=str(hallucinated_answer),
                label="HALLUCINATED",
                source_dataset=self.metadata.name,
                source_split=self.split,
                source_id=item_id,
                metadata={"query": query},
            )
        else:
            claim_text = str(raw_item.get("claim") or raw_item.get("response") or raw_item.get("answer") or "")
            raw_label = raw_item.get("label") or raw_item.get("hallucination")
            if raw_label is None:
                raise ValidationError(f"Missing label in HaluEval record: {raw_item}")

            key = str(raw_label).strip().lower()
            if key not in LABEL_MAP:
                raise ValidationError(
                    f"Unknown label '{raw_label}' in HaluEval record. Allowed source values: {list(LABEL_MAP.keys())}"
                )

            mapped_label = LABEL_MAP[key]
            yield ClaimVerificationRecord(
                record_id=item_id or f"{doc[:20]}_{claim_text[:20]}",
                document=doc,
                claim=claim_text,
                label=mapped_label,
                source_dataset=self.metadata.name,
                source_split=self.split,
                source_id=item_id,
                metadata={"query": query},
            )


__all__ = ["HaluEvalAdapter"]

